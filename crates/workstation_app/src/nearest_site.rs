//! Ctrl+click: load the nearest S-band NEXRAD.
//!
//! The word that carries the whole feature is *S-band*. Around every large
//! airport in the country there is also a TDWR, a C-band terminal radar
//! sitting fifteen to thirty kilometres from downtown — closer to the city
//! than the WSR-88D almost every time. A plain nearest-site search therefore
//! answers "Dallas" with TDAL, "Chicago" with TORD and "Atlanta" with TATL,
//! which is the opposite of what was asked for. A TDWR has roughly ninety
//! kilometres of Doppler range and attenuates badly in the heavy rain that a
//! severe-weather workflow is looking at, so it is a supplement, never the
//! radar the map falls back to (Vasiloff, S. V., 2001: Improving tornado
//! warnings with the Federal Aviation Administration's Terminal Doppler
//! Weather Radar. *Wea. Forecasting*, **16**; Istok, M. J., and coauthors,
//! 2009: Terminal Doppler Weather Radar for NWS operations. *25th Conf. on
//! IIPS*, Amer. Meteor. Soc.). Terminal radars are consequently not ranked
//! here at all — they are removed, and the ranking runs over WSR-88Ds only.
//!
//! This module is the decision and nothing else. It draws no pixels, holds no
//! egui context and starts no download: it takes a click's modifiers, a
//! clicked latitude and longitude, and the site catalog the application has
//! already loaded, and it answers which site to switch to. That is what makes
//! the part that is actually hard to get right — which radar wins where —
//! checkable against the real published catalog instead of against a picture.
//!
//! # Ported from BowEcho, and where this departs
//!
//! BowEcho spells the same gesture `ctrl_best_radar_click` (`app_ui/src/
//! main.rs`) feeding `best_radar_candidates` (`app_ui/src/sites_ui.rs`).
//! What it actually does:
//!
//!   * chord: `ctrl && !alt && !shift`;
//!   * take every site within 460 km whose catalogued kind is `Wsr88d` or
//!     `Intl` — `Tdwr` and `Research` are dropped before ranking;
//!   * score each one by the 0.5 degree beam-centre height at that range and
//!     sort ascending, so the pick is "the radar that sees lowest here";
//!   * classify TDWRs from an explicit id table, *not* from the `'T'`
//!     prefix, because TJUA (San Juan) is a T-prefixed WSR-88D;
//!   * and — the part that is easiest to leave out and that undoes the rest —
//!     take the click away from the site-marker hit-test while the chord is
//!     held (`plain_map_click_allowed`), so a marker cannot swallow the
//!     gesture. [`site_marker_click_allowed`] is that rule.
//!
//! The judgement ported here is all of that. Three deliberate departures:
//!
//!   1. **Ranking is by great-circle distance, and the beam height is
//!      reported rather than sorted on.** At a fixed elevation angle the
//!      4/3-earth beam height is strictly increasing in range, so ordering by
//!      beam height and ordering by distance are the same ordering; BowEcho's
//!      sort key implies the beam height adds information to the *choice*
//!      that it does not. [`SiteChoice::beam_height_m`] is carried anyway,
//!      because it is the number worth putting in the status line.
//!   2. **No international registry.** This workspace's catalog is the NWS
//!      station list only, so there is no `Intl` arm to keep.
//!   3. **Classification comes from the published `stationType`, not from a
//!      frozen prefix heuristic.** See below. The visible consequence is
//!      TLKA2: BowEcho lists it as a TDWR, because its seed table was
//!      generated by running the old `'T'`-prefix rule over the catalog.
//!      TLKA2 is a wind profiler.
//!
//! # How an S-band site is identified *here*
//!
//! The catalog this application carries ([`LocatedSite`]) has an id, a name
//! and a position. It has no band field and no network enum, because
//! `data_source::fetch_weather_gov_radar_sites` keeps only those four fields
//! out of the station feed. The feed itself does carry the discriminator —
//! `properties.stationType`, one of `WSR-88D`, `TDWR` or `Profiler` — so the
//! honest move is to bring that field's *content* into this module as data
//! and classify by id lookup, exactly as BowEcho does.
//!
//! [`TDWR_SITE_IDS`] and [`PROFILER_SITE_IDS`] are therefore transcriptions
//! of `https://api.weather.gov/radar/stations`, retrieved 2026-08-18: 208
//! stations, 159 `WSR-88D`, 45 `TDWR`, 4 `Profiler`. The transcription is
//! pinned by `classification_agrees_with_the_published_station_type`, which
//! replays the whole retrieved catalog through [`classify_site`].
//!
//! **How much work those two tables actually do, measured rather than
//! assumed.** Very little, today. Deleting either one changes no answer for
//! any of the 208 published stations, because the structural fallback below
//! already lands them all correctly: every published TDWR has a
//! four-character `T` id, and all four profilers have five-character ids.
//! `the_structural_rule_alone_already_classifies_the_published_catalog`
//! records that, so nobody reads the tables as the thing keeping TDAL out of
//! Dallas — the `'T'` prefix rule and the single TJUA exception
//! ([`S_BAND_WITH_A_TERMINAL_PREFIX`]) are what do that. The tables are kept
//! for the case the
//! structural rule cannot survive — a terminal radar commissioned under an id
//! that does not begin with `T`, which the fallback would silently admit as a
//! WSR-88D — but no test can pin that, because no id in the published catalog
//! needs it. What *is* pinned is the harm a table can do:
//! `no_exclusion_table_entry_is_a_published_wsr88d` fails if a typo ever puts
//! a WSR-88D id in one, which would quietly delete that radar from the
//! gesture.
//!
//! Two things the id alone will not tell you, and which is why the tables
//! exist:
//!
//!   * **TJUA is a WSR-88D.** San Juan's S-band radar has a `T` prefix. The
//!     TDWR twenty kilometres away is TSJU. A `'T'`-prefix rule leaves Puerto
//!     Rico with no radar at all under this gesture.
//!   * **`Profiler` rows are not radars.** AWPA2, HWPA2, ROCO2 and TLKA2 are
//!     wind profilers in the same feed and serve no Level II volume, so they
//!     must not be offered either.
//!
//! An id in neither table is classified structurally, and the fallback is
//! chosen to fail safe for this feature: an unrecognised four-character id
//! beginning with `T` is treated as terminal (it loses), an unrecognised id
//! that is not four characters is treated as neither (it loses), and only an
//! unrecognised four-character id with a non-`T` prefix is admitted as a
//! WSR-88D — which is the shape every new S-band site takes, KHDC being the
//! most recent example.

use eframe::egui;

use crate::sites_service::LocatedSite;
use crate::units::UnitSystem;

/// How far from the click a WSR-88D may be and still be offered, in
/// kilometres.
///
/// 460 km is the WSR-88D's unambiguous surveillance range — the outer edge of
/// the reflectivity sweep, beyond which the site has nothing to show at this
/// point (Crum, T. D., and R. L. Alberty, 1993: The WSR-88D and the WSR-88D
/// Operational Support Facility. *Bull. Amer. Meteor. Soc.*, **74**,
/// 1669-1687). Past it the answer is "no radar covers this", not "here is a
/// distant radar", and BowEcho fences the same gesture at the same range.
pub const MAX_SITE_RANGE_KM: f64 = 460.0;

/// The lowest surveillance tilt of every operational VCP, in degrees. Used
/// only to report how high the beam is over the clicked point.
const LOWEST_TILT_DEG: f64 = 0.5;

/// Generous ceiling for the ground-range-to-slant-range inversion. Larger
/// than [`MAX_SITE_RANGE_KM`] so the inversion is never the thing that
/// rejects a site.
const MAX_SLANT_RANGE_M: f64 = 1_000_000.0;

/// Mean earth radius for the great-circle distance, in kilometres. The IUGG
/// mean radius, matching `render2d::beam::EARTH_RADIUS_M`.
const EARTH_RADIUS_KM: f64 = 6371.0;

/// What a catalog id turns out to be.
///
/// Deliberately not `#[non_exhaustive]`: adding a class should be a compile
/// error at every site that decides what is loadable.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum SiteClass {
    /// S-band NEXRAD. The only class this gesture will load.
    Wsr88d,
    /// C-band FAA terminal Doppler radar.
    Tdwr,
    /// In the station feed but not a scanning weather radar: the four wind
    /// profilers, and anything whose id does not have a NEXRAD shape.
    Other,
}

impl SiteClass {
    /// Whether a site of this class may win a Ctrl+click.
    pub fn is_s_band_nexrad(self) -> bool {
        matches!(self, Self::Wsr88d)
    }
}

/// The 45 stations published as `stationType: "TDWR"`, plus one retired id.
///
/// TPBI is not in the current feed: West Palm Beach's terminal radar is
/// listed as TDJT. The old id is kept because
/// `data_source::FALLBACK_SITE_IDS` — the catalog this application falls back
/// to when the station feed cannot be reached — still carries TPBI, and a
/// site reaching this module from that path must classify the same way.
pub const TDWR_SITE_IDS: &[&str] = &[
    "TADW", "TATL", "TBNA", "TBOS", "TBWI", "TCLT", "TCMH", "TCVG", "TDAL", "TDAY", "TDCA", "TDEN",
    "TDFW", "TDJT", "TDTW", "TEWR", "TFLL", "THOU", "TIAD", "TIAH", "TICH", "TIDS", "TJFK", "TLAS",
    "TLVE", "TMCI", "TMCO", "TMDW", "TMEM", "TMIA", "TMKE", "TMSP", "TMSY", "TOKC", "TORD", "TPBI",
    "TPHL", "TPHX", "TPIT", "TRDU", "TSDF", "TSJU", "TSLC", "TSTL", "TTPA", "TTUL",
];

/// The four stations published as `stationType: "Profiler"`. They are in the
/// radar station feed, they have positions, and they are not radars.
pub const PROFILER_SITE_IDS: &[&str] = &["AWPA2", "HWPA2", "ROCO2", "TLKA2"];

/// The one S-band NEXRAD whose id begins with `T`: San Juan, Puerto Rico.
/// Called out by name because it is the single reason a prefix rule cannot be
/// used here.
pub const S_BAND_WITH_A_TERMINAL_PREFIX: &str = "TJUA";

/// What kind of station a catalog id names.
///
/// Table lookup first (that is the published `stationType`), then a
/// structural fallback for an id the tables have not seen. See the module
/// documentation for why the fallback leans the way it does.
pub fn classify_site(id: &str) -> SiteClass {
    let id = id.trim().to_ascii_uppercase();
    if PROFILER_SITE_IDS.contains(&id.as_str()) {
        return SiteClass::Other;
    }
    if TDWR_SITE_IDS.contains(&id.as_str()) {
        return SiteClass::Tdwr;
    }
    if id == S_BAND_WITH_A_TERMINAL_PREFIX {
        return SiteClass::Wsr88d;
    }
    let bytes = id.as_bytes();
    if bytes.len() != 4 || !bytes.iter().all(u8::is_ascii_alphanumeric) {
        return SiteClass::Other;
    }
    if bytes[0] == b'T' {
        SiteClass::Tdwr
    } else {
        SiteClass::Wsr88d
    }
}

/// Whether these modifiers are the "nearest S-band radar" chord.
///
/// **Ctrl alone, and nothing else with it.** Ported unchanged from BowEcho's
/// `ctrl_best_radar_click`, which is `ctrl && !alt && !shift`, so an analyst
/// moving between the two applications keeps one habit.
///
/// What this must not disturb, all of it checked in this module's tests:
///
///   * **Ctrl+scroll is the pane zoom** (`pane_canvas::wheel_zoom_factor`).
///     No conflict: that reads `Event::MouseWheel`, this reads a pointer
///     click. The two can even happen in the same frame — Ctrl held, wheel
///     spun, button clicked — and both are correct.
///   * **Plain drag pans and plain double-click resets the camera**
///     (`pane_canvas::draw_pane`). Both are unmodified gestures, so requiring
///     Ctrl keeps them clear; the double-click case additionally needs the
///     call site to stand down, which is what [`nearest_s_band_click`] is
///     for.
///   * **Ctrl+Shift and Ctrl+Alt are refused.** BowEcho's own tests assert
///     this and it is asserted again below. Those chords are spoken for in
///     the sibling application, and a chord that means one thing in BowEcho
///     must not mean a different thing here.
///
/// On macOS `modifiers.command` is the Command key and `modifiers.ctrl` is
/// the physical Control key; on Windows and Linux egui reports `command` as a
/// mirror of `ctrl`. Accepting either means the Windows and Linux behaviour
/// is exactly `ctrl` — bit-for-bit BowEcho's rule, on the platform this
/// application ships on — while a Mac gets Command+click as well. Command is
/// admitted deliberately rather than left out: macOS routes Control+click to
/// the *secondary* button at the window-server level, so on that platform a
/// Ctrl-only rule can be swallowed before egui ever sees a primary click, and
/// Command+click is the gesture a Mac user reaches for anyway.
pub fn is_nearest_s_band_chord(modifiers: egui::Modifiers) -> bool {
    (modifiers.ctrl || modifiers.command) && !modifiers.shift && !modifiers.alt
}

/// Whether this frame's pane click is the "nearest S-band radar" gesture.
///
/// The extra arguments are the collision handling, in one place instead of
/// spread across the call sites: the gesture takes a *single* primary click
/// only.
///
/// `double_clicked` is refused, and it is worth being exact about what that
/// does and does not buy, because it is easy to claim more. egui computes
/// `Response::double_clicked` as `clicked && pointer.button_double_clicked`
/// (`egui-0.34.3/src/response.rs`), so the flag can only ever be raised on
/// the *second* release — the first release of a double-click is an ordinary
/// `clicked()` with `double_clicked()` still false. A Ctrl+double-click
/// therefore still loads a radar on the first release and still resets the
/// camera on the second; no predicate reading one frame at a time can
/// prevent that, because at the first release the second click has not
/// happened yet. What this argument does prevent is the *second* release
/// kicking a redundant second load of the same site on top of the reset,
/// which is a visible stutter in the status line and one more cancelled
/// download.
pub fn nearest_s_band_click(
    modifiers: egui::Modifiers,
    primary_clicked: bool,
    double_clicked: bool,
) -> bool {
    primary_clicked && !double_clicked && is_nearest_s_band_chord(modifiers)
}

/// Whether a click on a radar site marker may be honoured this frame.
///
/// **This is the precedence rule, and getting it backwards silently undoes
/// the whole feature.** The pane draws a marker for every catalog site and
/// hit-tests a halo of [`SITE_MARKER_HIT_POINTS`] around each one
/// (`pane_canvas::draw_radar_sites`). That halo is measured in screen
/// points, so at a wide zoom it covers a great deal of ground: at the pane's
/// own opening scale of [`STARTUP_KM_PER_POINT`] it is a
/// [`startup_marker_halo_km`] radius circle. Every TDWR this feature exists
/// to beat sits inside that circle of its downtown — Dallas 23 km, Chicago
/// 21 km, Atlanta 16 km, San Juan 8 km, all against a 36 km halo — so a call
/// site that lets a marker hit win over this gesture answers a Ctrl+click on
/// downtown Dallas with TDAL, which is exactly the complaint that produced
/// the feature.
///
/// BowEcho settles this the same way and does it in the predicate rather
/// than at the call site: `plain_map_click_allowed`
/// (`app_ui/src/main.rs:46693`) is
/// `!shift && !ctrl_best_radar_click(modifiers) && !alt_model_sounding(..)`,
/// and the marker branch is gated on it, so a held Ctrl takes the marker
/// hit-test out of the running entirely before `handle_marker_click` is
/// reached. An unmodified click still belongs to the marker: clicking KTLX's
/// box is the quickest way to load KTLX, and this gesture does not want it.
pub fn site_marker_click_allowed(modifiers: egui::Modifiers) -> bool {
    !is_nearest_s_band_chord(modifiers)
}

/// Radius in screen points within which `pane_canvas::draw_radar_sites`
/// counts a click as landing on a site marker: half the shipped marker size
/// (5.0) plus `pane_canvas::SITE_CLICK_SLACK` (4.0). Restated here because
/// this module must not depend on the pane. The test named
/// `the_marker_halo_this_module_assumes_is_the_one_the_pane_uses` recomputes
/// it from those two and fails if either moves.
///
/// The marker's size is a setting (Readout & annotation), so an analyst who
/// enlarges it enlarges the halo with it. This constant is the SHIPPED halo,
/// which is what the Ctrl+click rule below is argued against - and the rule
/// only gets safer as the marker grows, because a bigger marker is a bigger
/// thing to have deliberately clicked.
/// Test-facing: nothing in the shipping path reads these four. They exist
/// so the assumption this module makes about the pane is written down and
/// checked, which is why they are gated rather than silenced.
#[cfg(test)]
pub const SITE_MARKER_HIT_POINTS: f64 = 9.0;

/// The scale the application opens a pane at, in kilometres per screen
/// point: `app::PLACEHOLDER_KM_PER_POINT`. Restated for the same reason, and
/// pinned by the same test.
#[cfg(test)]
pub const STARTUP_KM_PER_POINT: f64 = 4.0;

/// Ground radius of the site-marker halo at a given scale, in kilometres.
///
/// The number that makes [`site_marker_click_allowed`] necessary rather than
/// tidy: a screen-space hit radius is a large geographic one whenever the
/// pane is zoomed out.
#[cfg(test)]
pub fn marker_halo_km(km_per_point: f64) -> f64 {
    SITE_MARKER_HIT_POINTS * km_per_point
}

/// [`marker_halo_km`] at the scale the application actually opens on: 36 km.
#[cfg(test)]
pub fn startup_marker_halo_km() -> f64 {
    marker_halo_km(STARTUP_KM_PER_POINT)
}

/// The site a Ctrl+click resolved to.
#[derive(Clone, Debug, PartialEq)]
pub struct SiteChoice {
    /// Catalog id, as the catalog spells it — what `App::start_live` wants.
    pub id: String,
    pub name: Option<String>,
    /// Great-circle distance from the click to the antenna, kilometres.
    pub distance_km: f64,
    /// Height of the 0.5 degree beam centre above the antenna over the
    /// clicked point, metres. Reported, not ranked on; see the module
    /// documentation.
    pub beam_height_m: f64,
}

impl SiteChoice {
    /// The status line announcing this choice.
    ///
    /// It lives here rather than at the call site because the distance and the
    /// beam height are the evidence for the choice, and an operator who asked
    /// for the nearest S-band radar and got one 300 km away needs to see that
    /// in the same breath as the id.
    ///
    /// The two figures are written in the analyst's own units. The RANKING
    /// above is untouched by them: the winner is chosen on kilometres from a
    /// great circle, and this is the last step before the numbers become
    /// characters. Under [`UnitSystem::default`] the line is what it always
    /// was, character for character.
    pub fn status_line(&self, units: UnitSystem) -> String {
        format!(
            "{} - nearest WSR-88D, {}, 0.5 deg beam {}",
            self.id,
            units.distance(self.distance_km, 0),
            units.altitude(self.beam_height_m, 1)
        )
    }
}

/// The status line for a click with no S-band radar in range.
///
/// The fence itself is 460 km — the WSR-88D's surveillance range, a physical
/// fact and not a setting — but the analyst is told about it in whatever unit
/// they are reading the pane in.
pub fn no_site_in_range_status(units: UnitSystem) -> String {
    format!(
        "No WSR-88D within {} of that point",
        units.distance(MAX_SITE_RANGE_KM, 0)
    )
}

/// Great-circle distance between two positions, in kilometres.
///
/// Haversine on the R = 6371 km sphere, in the `atan2` form that stays
/// accurate for the small separations this feature actually deals in
/// (Sinnott, R. W., 1984: Virtues of the Haversine. *Sky and Telescope*,
/// **68**(2), 159). A planar approximation is not usable here: it is the
/// `cos(latitude)` term that makes a degree of longitude at Kodiak a little
/// over half of what it is at Key West, and without it the radar nearest
/// Kodiak comes out as PAHG when it is PAKC, 66 km closer
/// (`a_planar_nearest_would_pick_the_wrong_alaskan_radar`).
///
/// A sphere here is deliberately mixed with an ellipsoid upstream, and the
/// size of that mismatch was measured rather than argued. The lat/lon the
/// application hands in comes from `map_scene::RadarProjection::
/// world_to_lon_lat`, a Vincenty direct geodesic on WGS-84; ranking it on a
/// sphere is only safe if the two never disagree about the *winner*. Over the
/// 159 S-band sites in the shipped site cache and a 0.25 degree CONUS grid
/// (24 885 clicks, 24-50 N, 66-125 W), the sphere and a WGS-84 inverse
/// geodesic choose a different radar at 47 points, 0.19 per cent: 14 of them
/// sit within a kilometre of the 460 km fence over open water or northern
/// Mexico, and at the other 33 the two candidates are within 0.86 km of each
/// other, which is a tie in every sense that matters to an analyst. Going to
/// an ellipsoid here would change which of two equidistant radars is offered
/// and nothing else, so it is not worth the second geodesic implementation.
pub fn great_circle_km(lat_a_deg: f64, lon_a_deg: f64, lat_b_deg: f64, lon_b_deg: f64) -> f64 {
    let d_lat = (lat_b_deg - lat_a_deg).to_radians();
    let d_lon = (lon_b_deg - lon_a_deg).to_radians();
    let lat_a = lat_a_deg.to_radians();
    let lat_b = lat_b_deg.to_radians();
    let chord =
        (d_lat * 0.5).sin().powi(2) + lat_a.cos() * lat_b.cos() * (d_lon * 0.5).sin().powi(2);
    2.0 * EARTH_RADIUS_KM * chord.sqrt().atan2((1.0 - chord).max(0.0).sqrt())
}

/// Height of the 0.5 degree beam centre over a point `distance_km` away
/// across the ground, in metres above the antenna.
///
/// The ground distance is inverted to a slant range first
/// (`render2d::beam::slant_range_for_ground_arc_m`) rather than being passed
/// in as if it were one, so the number is the 4/3-effective-earth geometry
/// the rest of this workspace draws with (Doviak, R. J., and D. S. Zrnic,
/// 1993: *Doppler Radar and Weather Observations*, 2nd ed., Academic Press,
/// eqs. 2.28b and 2.28c).
fn lowest_beam_height_m(distance_km: f64) -> f64 {
    let ground_m = distance_km * 1000.0;
    let slant_m =
        render2d::beam::slant_range_for_ground_arc_m(ground_m, LOWEST_TILT_DEG, MAX_SLANT_RANGE_M)
            .unwrap_or(ground_m);
    render2d::beam::beam_height_arl_m(slant_m, LOWEST_TILT_DEG)
}

/// The WSR-88D to load for a click at `latitude_deg`, `longitude_deg`.
///
/// Nearest by great-circle distance among the catalog entries that
/// [`classify_site`] admits as S-band, within [`MAX_SITE_RANGE_KM`].
/// Terminal radars and profilers never compete, which is the entire point of
/// the gesture.
///
/// `None` means no WSR-88D covers the click — an ocean click, a click in
/// central Asia, or a click made before the site directory has arrived. The
/// caller should say so rather than loading something.
///
/// Rejected without looking at the catalog: a non-finite click, and a
/// latitude outside +/-90. Skipped inside the catalog: any entry with a
/// non-finite or out-of-range position. Longitude needs no wrapping — the
/// haversine's longitude term is periodic, so a click at 190 E and a click at
/// -170 E give identical distances.
///
/// Exact distance ties break on the smaller id, so the answer does not depend
/// on the order the catalog happens to arrive in.
pub fn nearest_s_band_site(
    latitude_deg: f64,
    longitude_deg: f64,
    sites: &[LocatedSite],
) -> Option<SiteChoice> {
    if !latitude_deg.is_finite() || !longitude_deg.is_finite() || latitude_deg.abs() > 90.0 {
        return None;
    }
    let mut best: Option<(f64, &LocatedSite)> = None;
    for site in sites {
        if !classify_site(&site.id).is_s_band_nexrad() {
            continue;
        }
        if !site.latitude_deg.is_finite()
            || !site.longitude_deg.is_finite()
            || site.latitude_deg.abs() > 90.0
        {
            continue;
        }
        let distance_km = great_circle_km(
            latitude_deg,
            longitude_deg,
            site.latitude_deg,
            site.longitude_deg,
        );
        if !distance_km.is_finite() || distance_km > MAX_SITE_RANGE_KM {
            continue;
        }
        let better = match &best {
            None => true,
            Some((best_km, best_site)) => {
                distance_km < *best_km
                    || (distance_km == *best_km && site.id.as_str() < best_site.id.as_str())
            }
        };
        if better {
            best = Some((distance_km, site));
        }
    }
    let (distance_km, site) = best?;
    Some(SiteChoice {
        id: site.id.clone(),
        name: site.name.clone(),
        distance_km,
        beam_height_m: lowest_beam_height_m(distance_km),
    })
}

/// The real NWS radar-station catalog, transcribed verbatim from
/// `https://api.weather.gov/radar/stations` on 2026-08-18: every station
/// the feed publishes, with the position and the `stationType` it
/// publishes. Columns are id, latitude, longitude, name, station type.
///
/// It is embedded rather than fetched so the tests are hermetic and
/// offline, and it is the whole catalog rather than a handful of rows so
/// that "the nearest WSR-88D to downtown Dallas" is a real answer over
/// the real network and not an artifact of which sites got listed.
/// `the_shipped_site_cache_agrees_with_the_transcript` re-checks it
/// against the file this application actually reads, when that file is on
/// the machine running the tests.
///
/// Test-only, but at module level rather than inside `mod tests`: the
/// catalogue is the shipped station table, and `north_up`'s bound proofs
/// have to sweep every row of it rather than a mid-latitude handful. See
/// `crate::north_up` for what they measure.
