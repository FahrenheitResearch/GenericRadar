    /// What the two id tables are actually worth today: nothing, over the
    /// published catalog. Recorded so the module is not read as resting on
    /// them.
    ///
    /// Reverting either table one at a time leaves all 27 tests passing,
    /// because every published TDWR has a four-character `T` id and all four
    /// profilers have five-character ids, so the structural fallback lands
    /// them anyway. This says that in the assertion rather than leaving it to
    /// be rediscovered: the thing keeping TDAL out of Dallas is the `'T'`
    /// prefix rule plus the one TJUA exception.
    #[test]
    fn the_structural_rule_alone_already_classifies_the_published_catalog() {
        fn structural_only(id: &str) -> SiteClass {
            let id = id.trim().to_ascii_uppercase();
            if id == S_BAND_WITH_A_TERMINAL_PREFIX {
                return SiteClass::Wsr88d;
            }
            let bytes = id.as_bytes();
            if bytes.len() != 4 || !bytes.iter().all(u8::is_ascii_alphanumeric) {
                return SiteClass::Other;
            }
            if bytes[0] == b'T' {
                SiteClass::Tdwr
            } else {
                SiteClass::Wsr88d
            }
        }
        let rows = real_catalog();
        let mut terminals = 0_usize;
        for row in &rows {
            let structural = structural_only(&row.site.id);
            assert_eq!(
                structural,
                classify_site(&row.site.id),
                "{} ({}): the tables and the structural rule must agree, or one \
                 of the two is the thing actually deciding",
                row.site.id,
                row.station_type
            );
            if row.station_type == "TDWR" {
                terminals += 1;
                assert!(!structural.is_s_band_nexrad(), "{}", row.site.id);
            }
        }
        assert_eq!(terminals, 45);
        println!(
            "the structural rule alone classifies all {} published stations correctly; \
             the id tables change no present answer",
            rows.len()
        );
    }

